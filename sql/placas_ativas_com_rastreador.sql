SELECT DISTINCT
    iv.chassi AS chassi,
    cata.FANTASIA AS unidade,
    cat.NOME AS cooperado,
    ir.ID AS matricula,
    irs.ID AS conjunto,
    CAST(COALESCE(irs.DATE_INITAL_EFFECT, DATE_ADD('day', -364, irs.DATE_FINAL_EFFECT)) AS date) AS inicio_de_vigencia,
    iv.BOARD AS placas
FROM
    INSURANCE_REGISTRATION ir
    LEFT JOIN CLIENTE cli ON cli.CODIGO = ir.CUSTOMER_ID
    LEFT JOIN CATALOGO cat ON cat.CNPJ_CPF = cli.CNPJ_CPF
    LEFT JOIN INSURANCE_REG_SET irs ON irs.PARENT = ir.ID
    LEFT JOIN INSURANCE_STATUS iss ON iss.ID = irs.ID_STATUS
    LEFT JOIN REPRESENTANTE r ON r.CODIGO = irs.ID_UNITY
    LEFT JOIN CATALOGO cata ON cata.CNPJ_CPF = r.CNPJ_CPF
    LEFT JOIN INSURANCE_REG_SET_COVERAGE irsc ON irsc.PARENT = irs.ID
    LEFT JOIN PRICE_LIST_BENEFITS plb ON plb.ID = irsc.ID_PRICE_LIST
    LEFT JOIN TYPE_CATEGORY tc ON tc.ID = plb.ID_TYPE_CATEGORY
    LEFT JOIN CATEGORY c ON c.ID = tc.ID_CATEGORY
    LEFT JOIN BENEFITS b ON b.ID = c.ID_BENEFITS
    LEFT JOIN INSURANCE_VEHICLE iv ON iv.ID = irsc.ID_VEHICLE
WHERE
    iss.DESCRIPTION = 'ATIVO'
    AND b.ID = 8
    AND irsc.ID_STATUS = 11
ORDER BY
    irs.ID;
